"""Encoder/Decoder and the Chain Rule: the numbers of the worked example drawn in diagrams/embedding_spaces/autoencoder.tex.

Trains the autoencoder of the section (one hidden layer, 64 -> 128 -> 16 -> 128 -> 64; the first seed of
encoders_digits_reconstruction.py, which is imported, so it is the same network as the one of the reconstruction figure and of the table),
and passes one held-out image through it: the digit 7 of the figure (the first 7 of the held-out images). Writes
../../diagrams/embedding_spaces/autoencoder.inc, which the diagram includes:
  \\xpix, \\xhatpix   the 64 pixels of the input and of the reconstruction (clipped to [0, 1]), as integer percentages of black
  \\errpix           the squared error of each pixel, as a percentage of the largest one (\\errmax)
  \\codepix          the 16 coordinates of the code, as integer percentages of the largest absolute one (\\codemax)
  \\lossval          the squared error per pixel of the image (the loss L)
The .inc is committed, like the figures, so that `make diagrams` does not need to train anything.
"""
from pathlib import Path

import numpy as np

import encoders_digits_reconstruction as rec

DIGIT = 7
DIAGRAMS = Path("../../diagrams/embedding_spaces")

if __name__ == "__main__":
    result = rec.train(("autoencoder", 0))
    params, relu = result["params"], rec.layers(rec.MODELS["autoencoder"][0], False)
    i = int(np.argmax(rec.base.labels_test == DIGIT))
    x = rec.X_TEST[i][None]
    out, acts = rec.forward(params, relu, x)
    code, x_hat = acts[2][0], out[0]  # acts[0] is the input, acts[2] the output of the layer that writes the 16 coordinates
    squared = (x_hat - x[0]) ** 2
    loss = float(squared.mean())
    assert np.isclose(loss, result["test"][i]), "the example is not the held-out image of the trained network"

    def percent(v: np.ndarray, scale: float = 1.0) -> str:
        return ",".join(str(int(round(100 * t))) for t in v / scale)

    text = (f"% Generated by code/embedding_spaces/encoders_digits_diagram.py: do not edit.\n"
            f"\\def\\xpix{{{percent(np.clip(x[0], 0, 1))}}}\n"
            f"\\def\\xhatpix{{{percent(np.clip(x_hat, 0, 1))}}}\n"
            f"\\def\\errpix{{{percent(squared, squared.max())}}}\n"
            f"\\def\\errmax{{{squared.max():.2f}}}\n"
            f"\\def\\codepix{{{percent(code, np.abs(code).max())}}}\n"
            f"\\def\\codemax{{{np.abs(code).max():.1f}}}\n"
            f"\\def\\lossval{{{loss:.4f}}}\n")
    DIAGRAMS.mkdir(parents=True, exist_ok=True)
    (DIAGRAMS / "autoencoder.inc").write_text(text)
    print(f"held-out image {i} (digit {DIGIT}): loss {loss:.4f}, largest squared error {squared.max():.3f}, "
          f"code in [{code.min():.2f}, {code.max():.2f}]")
    print(f"saved {(DIAGRAMS / 'autoencoder.inc').resolve()}")
